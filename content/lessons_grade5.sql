INSERT INTO lesson_content_history (content_id, game_id, lesson_no, title, summary, body, read_time, status, version_no)
SELECT lc.content_id, lc.game_id, lc.lesson_no, lc.title, lc.summary, lc.body, lc.read_time, lc.status, lc.version_no
FROM lesson_content lc JOIN new_lessons n ON n.game_id = lc.game_id
WHERE lc.lesson_no = 1;

INSERT INTO lesson_content (game_id, lesson_no, title, summary, read_time, body, status, version_no, published_at)
SELECT game_id, 1, title, summary, read_time, trim(body), 'published', 1, NOW() FROM new_lessons
ON CONFLICT (game_id, lesson_no) DO UPDATE SET
    title = EXCLUDED.title,
    summary = EXCLUDED.summary,
    read_time = EXCLUDED.read_time,
    body = EXCLUDED.body,
    status = 'published',
    version_no = lesson_content.version_no + 1,
    published_at = NOW(),
    updated_at = NOW();

COMMIT;
