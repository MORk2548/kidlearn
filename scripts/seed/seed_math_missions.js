// Writes api/kidlearn_patch_math_missions.sql: replaces the grade-5 math questions with
// multi-step missions stored as JSON in questions.question_img, so teachers can edit them.
// Usage: node scripts/seed/seed_math_missions.js [missions per level, default 20]
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..', '..');
const sandbox = { window: {}, Math, console };
vm.runInNewContext(fs.readFileSync(path.join(root, 'js', 'math_questions.js'), 'utf8'), sandbox);
const kit = sandbox.window.MathKit;

const perLevel = Number(process.argv[2]) || 20;
const levels = ['easy', 'medium', 'hard', 'challenge'];
const codes = Object.keys(kit.GENERATORS);
const sql = value => `'${String(value).replace(/'/g, "''")}'`;

const rows = [];
for (const code of codes) {
  let order = 1;
  for (const level of levels) {
    for (let i = 0; i < perLevel; i++) {
      const { title, difficulty, ...body } = kit.makeMission(code, level, i);
      const errors = kit.validateMission({ title, difficulty, ...body });
      if (errors.length) throw new Error(`${code}/${level}: ${errors.join(', ')}`);
      rows.push(`(${sql(code)}, ${sql(title)}, ${sql(JSON.stringify(body))}, ${sql(difficulty)}, ${order++})`);
    }
  }
}

const codeList = codes.map(sql).join(', ');
const out = `-- Generated by scripts/seed/seed_math_missions.js. Apply after api/kidlearn_patch_math_grade5.sql.
-- Replaces the untouched questions of the six grade-5 math games with ${perLevel} new missions per level.
-- Rows a teacher created or edited (created_by or updated_by set) are kept.
-- Each mission is one questions row: question_text is the title, question_img holds the mission JSON,
-- and answers rows are not used.
BEGIN;

ALTER TABLE questions DROP CONSTRAINT IF EXISTS questions_difficulty_check;
ALTER TABLE questions ADD CONSTRAINT questions_difficulty_check
    CHECK (difficulty IN ('easy', 'medium', 'hard', 'challenge'));

DELETE FROM questions
WHERE game_id IN (SELECT game_id FROM games WHERE game_code IN (${codeList}))
  AND created_by IS NULL AND updated_by IS NULL;

INSERT INTO questions (game_id, question_text, question_img, difficulty, order_no, point)
SELECT g.game_id, m.title, m.body, m.difficulty, m.order_no, 10
FROM (VALUES
${rows.join(',\n')}
) AS m(game_code, title, body, difficulty, order_no)
JOIN games g ON g.game_code = m.game_code;

UPDATE games SET question_count = NULL WHERE game_code IN (${codeList});

COMMIT;
`;
const target = path.join(root, 'api', 'kidlearn_patch_math_missions.sql');
fs.writeFileSync(target, out);
console.log(`Wrote ${rows.length} missions (${(out.length / 1024).toFixed(0)} KB) to ${path.relative(root, target)}`);
